#pragma once
/* v2.19: дальность прорисовки (draw_distance) — чистая математика расширенного обхода клеток, без данных игры и без платформы.
   Оригинал (Game.exe, D3D-путь): клетка карты 3000 единиц (P80_Cell), окно обхода P89_DrawMap (004ee8f4) — 31×31 клеток вокруг клетки
   камеры по таблице FRUSTRUM.DAT (256 секторов курса, клин), PVS P89_VisMask — тоже 31×31 (P21_GridRadius = 45000 / P80_Cell = 15);
   дальняя плоскость P11_01270c24 = 45000 (опция «дальность» 15000..45000, шаг 3000), её копия Q01270C24 — отсечение полигонов;
   таблица 1/z 00ba53a0 — 0xdbba = 56250 элементов (z камеры > 56250 в оригинале не бывает).
   Множитель m (1.0 — оригинал, до RE_DD_MAX): радиус обхода R = round(15·m) клеток; внутри 31×31 — FRUSTRUM.DAT (+Hor+) и PVS как
   в оригинале, снаружи — своя проверка конуса: курс — направление центроида клеток сектора FRUSTRUM.DAT, полуугол — боковые плоскости
   (aspect.h) + угловой размер клетки и смещение камеры внутри клетки. FRUSTRUM.DAT не меняется. */
#include <stdint.h>

#define RE_DD_MAX    4.0
#define RE_DD_BASE_R 15          /* радиус окна оригинала в клетках (31×31) */

double re_dd_clamp(double m);                 /* NaN/≤1 → 1, > RE_DD_MAX → RE_DD_MAX */
int    re_dd_radius(double m);                /* радиус обхода в клетках: 15 при m = 1, round(15·m) */
/* курс сектора по маске 31×31 (центроид клеток, кроме центральной): единичный (hx, hy) в осях (столбец, строка); 0 — пустая маска.
   Для косых секторов центроид клина, обрезанного квадратом, смещён к диагонали — поэтому курс камеры берётся из re_dd_heading_tab. */
int    re_dd_heading(const uint8_t *mask31, double *hx, double *hy);
/* курс камеры по углу ang (4096 единиц на оборот, P59_AngB) в осях таблицы FRUSTRUM.DAT: оси — центроиды секторов 0 и 64 (они
   симметричны относительно оси, обрезка квадратом их не смещает), h = cos φ·e0 + sin φ·e64; 0 — таблица пуста */
int    re_dd_heading_tab(const uint8_t *tab, int ang, double *hx, double *hy);
/* клетка со смещением (dx, dy) от клетки камеры видна в конусе: |d| ≤ R + 0.5 и угол к курсу ≤ th + запас клетки (asin(1.5/|d|));
   соседние клетки (|d| < 2) — всегда */
int    re_dd_cell_in(int dx, int dy, double hx, double hy, double th, int R);
/* смещения клеток вокруг камеры в квадрате (2R+1)², отсортированные по расстоянию (ближние раньше — списки классов по 0x400 не
   вытесняют ближние объекты дальними); out — (2R+1)² пар (dx, dy); возвращает число */
/* решение обхода для клетки (dx, dy) при радиусе R: внутри 31×31 — маска FRUSTRUM.DAT (mask31, строки×столбцы, центр 15,15) или,
   за кругом 14.5 (стык и углы квадрата), конус; снаружи — конус. PVS (31×31) проверяет вызывающий для клеток внутри квадрата. */
int    re_dd_visit(int dx, int dy, const uint8_t *mask31, double hx, double hy, double th, int R);
int    re_dd_order(int R, int8_t *out);
/* 1/z за пределами таблицы оригинала: k / zi (k — 0125f3e0, как при заполнении таблицы 00526427), 0 при zi ≤ 0 */
float  re_dd_oow(float k, int32_t zi);
/* размер таблицы 1/z, нужный для дальней плоскости far: оригинальные 0xdbba, если far в неё помещается, иначе far·1.25 */
int32_t re_dd_oow_n(double far);
int    re_dd_selftest(void);                  /* 0 — ок, иначе номер проваленной проверки */

/* 1 — идёт основной 3D-вид с расширенной дальностью (P132_GameDraw, native, m > 1): дальняя плоскость P11_01270c24/Q01270C24
   умножена на m, P89_DrawMap обходит клетки за 31×31; вне него (зеркало, меню, логика) — 0 */
extern int re_dd_on;
/* множитель видимости для порогов LOD/деталей, пока re_dd_on (иначе 1) */
float  re_dd_vis(void);
/* текущий множитель (native — driver.cfg draw_distance / RE_DRAW_DIST, hook — всегда 1.0) */
double re_draw_distance(void);
#ifndef RE_HOOK_BUILD
void   re_dd_warm(void);                      /* ported89.c: разобрать все нужные блоки радиуса сразу (проверка рендера) */
#endif
