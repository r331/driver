/* ported57.c (English overview) — the generic menu-screen loop and fourteen screens built on it,
   director / high-score file I/O, small file helpers, texture-slot reset and the full-screen-map
   screen -> view conversion.  Menu screens: a table of entries (Game.exe .data address), a state word
   reset to 0, a two-address scroll/intro setup (Call0040CCB4), then each frame: messages
   (Call00522323), input (Call004E3391), one menu step (P57_MenuStep, 0 = keep going), draw
   (Call0040CB9F).  Result -1 means "back": the screen idles six frames (P57_MenuDone) and returns 0.
   TODO(RE): which screen each P57_MenuXXXXXX is has not been mapped yet. */
