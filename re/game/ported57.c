/* 0040cd17: SetMenuIdle — остановить таймер, 6 раз: сообщения, ввод, шаг i (0040cb9f читает его из 5f7e48). */
/* P57_MenuDone — Game.exe 0040cd17 ("SetMenuIdle").  Leaves a menu screen: stops the menu timer
   (Call004086EA, Ui0040C87A), then runs 6 frames of messages / input / draw with P45_Busy set and
   P45_Step = frame index (read by the draw routine 0040cb9f — the closing transition). */
void P57_MenuDone(void) {
  Call004086EA();
  Ui0040C87A();
  P45_Busy = 1;
  for (int32_t i = 0; i < MENU_IDLE_FRAMES; i++) {
    Call00522323();
    Call004E3391();
    P45_Step = i;
    Call0040CB9F();
  }
  P45_Busy = 0;
}

/* Общая часть: таблица пунктов, ожидание-прокрутка, опрос меню до ненулевого результата. state уже обнулён. */
/* Shared loop (inlined in each original screen): entry table tbl, state word (already zeroed), setup
   addresses a, b; returns the first non-zero P57_MenuStep result. */
static int32_t menu_run(uint32_t tbl, int32_t *state, uint32_t a, uint32_t b) {
  int32_t r;
  P57_MenuInit(tbl, 0);
  Call0040CCB4(a, b);
  for (;;) {
    Call00522323();
    Call004E3391();
    r = P57_MenuStep(tbl, state);
    if (r != 0) break;
    Call0040CB9F();
  }
  return r;
}
/* Shared exit: MENU_BACK -> closing transition and result 0; any other result is returned as is. */
static int32_t menu_end(int32_t r) {
  if (r == MENU_BACK) { P57_MenuDone(); r = 0; }
  return r;
}

