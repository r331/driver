#pragma once
/* v2.15: произвольное соотношение сторон (Hor+) — чистая математика, без данных игры и без платформы.
   Оригинал рисует 3D в кадре 640×480: центр проекции (320, 240) = P43_OffX/OffY (P110_ViewSetup 00425b12), фокус P43_ScaleA = 384
   (вертикальный FOV 2·atan(240/384) ≈ 64°, горизонтальный 2·atan(320/384) ≈ 79.6°), окно отсечения P110_Clip* 0..640 × 0..480,
   боковые плоскости пирамиды P82_FrustumSetup3D — нормали (±cos θ, 0, −sin θ) из FSIN.DAT[475] (θ = 41.7°: геометрия 39.8° + запас ≈ 1.9°)
   через точки (±320, 0, 384); отсечение клеток карты — FRUSTRUM.DAT, 256 секторов курса × 31×31 клеток (клин ≈ ±45°).
   Hor+: вертикаль как в оригинале (фокус 384, высота 480), логическая ширина 3D = 480·аспект = 640 + 2·S. Игра продолжает считать
   в координатах 640×480 с центром 320; 3D выходит за 0..640 на S слева (x < 0) и справа (x > 640), бэкенд сдвигает всё на +S.
   S = 0 — ровно оригинал (RE_ASPECT=4:3, окно 4:3 или уже — тогда letterbox, см. re_aspect_extra). */
#include <stdint.h>

#define RE_ASPECT_W     640
#define RE_ASPECT_H     480
#define RE_ASPECT_FOCAL 384.0
#define RE_ASPECT_MAX   4.0          /* шире 4:1 не расширяем (32:9 = 3.56 проходит) */

/* RE_ASPECT: NULL/""/"auto" → 0 (по окну); "4:3" / "W:H" / "1.78" → отношение > 0; ошибка → −1 */
double re_aspect_parse(const char *s);
/* целевое отношение сторон кадра: mode = результат re_aspect_parse; auto → dw/dh; ошибка → auto */
double re_aspect_target(int dw, int dh, double mode);
/* S — добавка логических пикселей с каждой стороны 640 для отношения aspect; 0 для aspect ≤ 4:3 (уже 4:3 — letterbox, вертикаль не растёт) */
int    re_aspect_extra(double aspect);
/* половина горизонтального угла боковых плоскостей (радианы) для полуширины 320 + S с запасом оригинала (S = 0 → θ из FSIN.DAT[475]) */
double re_aspect_half_angle(int S);
/* число дополнительных секторов FRUSTRUM.DAT (по 4096/256 = 16 единиц курса) с каждой стороны, чтобы клин покрыл угол для S */
int    re_aspect_sectors(int S);
/* объединение секторов sec−k..sec+k таблицы FRUSTRUM.DAT (tab: 256 записей по 0x80 байт: {первая строка, число строк,
   31 × {первый столбец, длина}}) в маску 31×31 (1 — клетка обходится); возвращает число клеток */
int    re_frustum_union(const uint8_t *tab, int sec, int k, uint8_t *mask);
/* самопроверка математики (без данных игры): 0 — ок, иначе номер проваленной проверки; используется selftest/inputtest */
int    re_aspect_selftest(void);

/* S текущего кадра для основного 3D-вида игры: native — plat_view_extra() при ширине кадра игры 640 (не зеркало), hook — 0 */
int    re_view_extra(void);
/* для проверок «точка на экране» в 3D-коде игры: левая граница вида −S, правая 640 + S; в hook — всегда 0 (оригинал) */
#ifndef RE_HOOK_BUILD
#define RE_VIEW_EX() re_view_extra()
#else
#define RE_VIEW_EX() 0
#endif
