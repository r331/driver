#!/usr/bin/env python3
"""Generate re/game/mscript_ops.h: mission-script (MScript) opcode names.

Source: the command table of Game.exe at .data 00563980 (P42_Cmds, 153 records of 0x110 bytes:
char name[0x100], int32 argc, int32 id, int32 size, int32 pad), read from the data image
re/game/data_image.c (itself generated from the user's Game.exe by tools/gen_data_init.py).
The enum value is the record's `id` — the opcode P146_ScriptCmd switches on (cmd[0]).
Usage: python3 tools/gen_mscript_ops.py  (from the repository root)
"""
import re, struct, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG_C = os.path.join(ROOT, 're', 'game', 'data_image.c')
OUT = os.path.join(ROOT, 're', 'game', 'mscript_ops.h')
BASE, TAB, N, REC = 0x00546000, 0x00563980, 153, 0x110

src = open(IMG_C).read()
m = re.search(r'uint8_t re_data_image\[(\d+)\] = \{', src)
body = src[m.end():src.index('};', m.end())]
img = bytes(int(x) for x in re.findall(r'\d+', body))

rows = []
for i in range(N):
    r = img[TAB - BASE + i * REC: TAB - BASE + (i + 1) * REC]
    name = r[:0x100].split(b'\0')[0].decode('latin1')
    argc, op, size, _ = struct.unpack('<iiii', r[0x100:0x110])
    if not name:
        break
    rows.append((name, op, argc, size))

seen = {}
lines = []
for name, op, argc, size in rows:
    ident = 'MS_' + re.sub(r'[^A-Z0-9_]', '_', name.upper())
    if op in seen:
        lines.append(f'  {ident:<28} = {op:3d},   /* 0x{op:02x}  alias of {seen[op]}; argc {argc}, size {size} */')
    else:
        seen[op] = ident
        lines.append(f'  {ident:<28} = {op:3d},   /* 0x{op:02x}  argc {argc}, size {size} */')

hdr = f"""/* mscript_ops.h — GENERATED by tools/gen_mscript_ops.py, do not edit.
 * Mission-script (MScript) opcodes: the keyword table of Game.exe at .data 00563980 (P42_Cmds).
 * Value = the opcode stored in cmd[0] of a compiled command and dispatched by P146_ScriptCmd
 * (004f8e0c).  argc / size are the table's own fields (argument count and size in bytes, 4 + 4 * argc
 * for fixed-length commands; variable-length ones such as SET or LOG store strings in place).
 * {len(rows)} keywords, {len(seen)} distinct opcodes. */
#pragma once

enum mscript_op {{
""" + '\n'.join(lines) + "\n};\n"
open(OUT, 'w').write(hdr)
print(f'wrote {OUT}: {len(rows)} keywords')
missing = sorted(set(range(max(seen) + 1)) - set(seen))
if missing:
    print('opcode values without a keyword:', missing)
